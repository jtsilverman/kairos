#!/usr/bin/env python3
"""thesis-exemplars: generate the blind sorter workflow with its body embedded.

One opus seat per name reads the REAL dossier by path and grades the four
tests plus the driver. No outcome reaches the workflow at all; the join to
the realized window happens in `sort_exemplars.py record`, in code, after
the run. The body lives in `.claude/agents/thesis-sorter.md` and the rubric
in `docs/four-tests.md`; both are embedded at generation time because the
agent registry serves session-cached bodies and cannot spawn a new type.

Usage:
    gen_sorter_workflow.py --out <path>.js
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import agent_bodies  # noqa: E402
import four_tests  # noqa: E402

def body() -> str:
    return agent_bodies.body("thesis-sorter") + "\n\n---\n\n" + four_tests.rubric()


_TEMPLATE = """\
export const meta = {
  name: 'thesis-sorter',
  description: 'thesis-exemplars: one blind opus read per real dossier, four graded tests plus the driver, no outcome in sight',
  phases: [
    { title: 'Blind read', detail: 'dossier only; the join to the realized window happens in code after the run' },
  ],
}

// GENERATED by scripts/gen_sorter_workflow.py — edit .claude/agents/thesis-sorter.md
// or docs/four-tests.md and regenerate; never edit BODY here.
const BODY = BODY_JSON

const input = args
if (!input || !input.asOf || !input.root) throw new Error('args.asOf and args.root are required')
if (!Array.isArray(input.names) || input.names.length === 0) {
  throw new Error('args.names required: [{ticker, docIds: "P1 Q1 ..."}]; run sort_exemplars.py prepare')
}
// Compact args: the path is derived here, the ids are split here. The
// outcome must never ride in; a row carrying it hands the blind reader the answer.
const names = input.names.map((n) => {
  if (!n.ticker || typeof n.docIds !== 'string' || !n.docIds.trim()) {
    throw new Error(`names[] needs ticker and docIds, got ${JSON.stringify(n)}`)
  }
  for (const k of ['alpha', 'beat', 'tickerReturn', 'spyReturn']) {
    if (k in n) throw new Error(`${n.ticker}: names[] carries ${k}; the sorter is blind`)
  }
  return {
    ticker: n.ticker, as_of: input.asOf,
    dossierPath: `${input.root}/dossiers/${input.dossierDir || `rewind-${input.asOf}`}/${n.ticker}.md`,
    docIds: n.docIds.trim().split(/\\s+/),
  }
})

// January 2026 cutoff, versioned id (probe-verified 2026-08-19).
const OPUS = 'claude-opus-4-8'

FOUR_TESTS_SCHEMA_JS
const sorterSchema = (ticker, asOf) => ({
  type: 'object',
  properties: {
    ticker: { type: 'string', enum: [ticker] },
    as_of: { type: 'string', enum: [asOf] },
    tests: TESTS,
    driver: { type: 'string', minLength: 40, maxLength: 500 },
    summary: { type: 'string', minLength: 120 },
  },
  required: ['ticker', 'as_of', 'tests', 'driver', 'summary'],
})

log(`sorter: ${names.length} blind reads for ${input.asOf}`)

const rows = await pipeline(
  names,
  (name) => agent(
    BODY + '\\n\\n---\\n\\n' +
    `Candidate ${name.ticker}, dossier compiled as of ${name.as_of}.\\n\\n` +
    `===== DOSSIER =====\\nRead this file IN FULL with the Read tool before ` +
    `any grade:\\n${name.dossierPath}\\n===== END DOSSIER =====\\n\\n` +
    `Valid citation doc ids: ${name.docIds.join(', ')}.\\n` +
    `Now grade the four tests, write the driver, write the summary, all via ` +
    `the schema. Use the Read tool for that one file and no other tool.`,
    { model: OPUS, effort: 'high', phase: 'Blind read',
      label: `sort:${name.ticker}@${name.as_of}`,
      schema: sorterSchema(name.ticker, name.as_of) }),
)

const done = rows.filter(Boolean)
const dropped = names.map((n) => n.ticker).filter((t) => !done.some((r) => r.ticker === t))
if (dropped.length) log(`WARNING: no grade for ${dropped.length} names, rerun them: ${dropped.join(' ')}`)
log(`${input.asOf}: ${done.length} of ${names.length} graded`)
return { asOf: input.asOf, dropped, rows: done }
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args(argv)
    script = _TEMPLATE.replace("FOUR_TESTS_SCHEMA_JS\n", four_tests.SCHEMA_JS)
    script = script.replace("BODY_JSON", json.dumps(body()))
    args.out.write_text(script)
    print(f"wrote {args.out} ({len(script)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
