#!/usr/bin/env python3
"""thesis-exemplars unit 8: generate the five-seat funnel workflow.

The panel of record (specs/thesis-exemplars.md, "The panel of record"):
per name, a sonnet bull and a sonnet bear argue the four tests in parallel;
a sonnet ruler reads the dossier and both cases and rules per test; the
PASS RULE is applied here, in code; on a pass, an opus editor checks both
cases against the dossier and the verdict seat writes the thesis, the
whole-company bear case, `shortlist` and the one `p_outperform`.

The agent registry serves session-cached bodies and cannot spawn a new
type, so the five `.claude/agents/*-seat.md` bodies (frontmatter stripped)
and the one rubric on disk, `docs/four-tests.md`, are embedded at
generation time. Bodies live in the .md files, the workflow SHAPE lives
here, and the emitted script is a build artifact.

Runtime `args.layer` picks what runs: `full` (default) is the funnel;
`middle` stops after the ruler and returns the cases; `verdict` takes each
name's stored cases by path (`casesPath`, which the editor reads after the
dossier) plus `rulings` and `overall`, and runs editor and verdict on every
name given, pass or not (layer 2's force-pass); `scripts/verdict_prepare.py`
writes those args.

A seat may never know the future of the date it judges: the generated
script holds each model's training cutoff and refuses a run whose as-of
falls before the verdict model's cutoff, on every launch.

Usage:
    gen_funnel_workflow.py --out <path>.js [--pass-rule overall|A|B]
                           [--verdict-model claude-fable-5]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import agent_bodies  # noqa: E402
import four_tests  # noqa: E402

SEATS = ("bull", "bear", "ruler", "editor", "verdict")
OPUS = "claude-opus-4-8"
# the verdict seat of record from 2026-09-15 (Jake): Fable 5, January 2026 cutoff, blind on every
# tuning date and June; the bare `fable` alias is Fable 5.1 (June 2026) and is refused there
VERDICT = "claude-fable-5"
PASS_RULES = ("overall", "A", "B")


def body(seat: str) -> str:
    """The seat body, frontmatter stripped, with the rubric appended."""
    return agent_bodies.body(f"{seat}-seat") + "\n\n---\n\n" + four_tests.rubric()


_TEMPLATE = """\
export const meta = {
  name: 'funnel',
  description: 'kairos funnel: sonnet bull, bear and ruler on every name, the pass rule in code, opus editor and the verdict on survivors',
  phases: [
    { title: 'Cases', detail: 'bull and bear argue the four tests, in parallel, sonnet' },
    { title: 'Ruler', detail: 'reads the dossier then both cases, rules per test, sonnet' },
    { title: 'Editor', detail: 'checks both cases against the dossier, survivors only, claude-opus-4-8' },
    { title: 'Verdict', detail: 'thesis, whole-company bear case, shortlist, p_outperform, survivors only' },
  ],
}

// GENERATED by scripts/gen_funnel_workflow.py — edit the .claude/agents/*-seat.md
// bodies or docs/four-tests.md and regenerate; never edit BODY here.
const BODY = {
  bull: BODY_BULL_JSON,
  bear: BODY_BEAR_JSON,
  ruler: BODY_RULER_JSON,
  editor: BODY_EDITOR_JSON,
  verdict: BODY_VERDICT_JSON,
  verdict_unruled: BODY_VERDICT_UNRULED_JSON,
}

// The pass rule, in code, never a model's call. overall: the ruler's one
// word on the whole is bull (Jake, 2026-09-12). A: bull on all four tests.
// B: bull on three and gap on one.
const PASS_RULE = 'PASS_RULE_VALUE'
const passes = (rulings, overall) => {
  if (PASS_RULE === 'overall') return overall === 'bull'
  const words = Object.values(rulings)
  const bulls = words.filter((w) => w === 'bull').length
  const gaps = words.filter((w) => w === 'gap').length
  if (PASS_RULE === 'A') return bulls === 4
  if (PASS_RULE === 'B') return bulls === 4 || (bulls === 3 && gaps === 1)
  throw new Error(`unknown PASS_RULE ${PASS_RULE}`)
}

const input = args
if (!input || !input.asOf || !input.root) throw new Error('args.asOf and args.root are required')
if (!Array.isArray(input.names) || input.names.length === 0) {
  throw new Error('args.names required: [{ticker, docIds: "P1 Q1 ..."}]; run scripts/panel_prepare.py')
}
const LAYER = input.layer || 'full'
if (!['full', 'middle', 'verdict', 'editor', 'decide'].includes(LAYER)) throw new Error(`args.layer must be full, middle, verdict, editor or decide, got ${LAYER}`)
// Unit 11j: the verdict with the ruler's words withheld. Set by the generator;
// false is the funnel of record.
const WITHHOLD_RULINGS = WITHHOLD_RULINGS_VALUE
const names = input.names.map((n) => {
  if (!n.ticker || typeof n.docIds !== 'string' || !n.docIds.trim()) {
    throw new Error(`names[] needs ticker and docIds, got ${JSON.stringify(n)}`)
  }
  for (const k of ['alpha', 'beat', 'class']) {
    if (k in n) throw new Error(`${n.ticker}: names[] carries ${k}; the funnel is blind`)
  }
  if ((LAYER === 'verdict' || LAYER === 'editor') && !(typeof n.casesPath === 'string' && n.rulings && n.overall)) {
    throw new Error(`${n.ticker}: layer verdict needs names[].casesPath, rulings and overall (verdict_prepare.py)`)
  }
  if (LAYER === 'decide' && !(n.edited && n.rulings && n.overall)) {
    throw new Error(`${n.ticker}: layer decide needs names[].edited (the editor's checked cases), rulings and overall`)
  }
  return {
    slug: n.ticker, as_of: input.asOf,
    dossierPath: `${input.root}/dossiers/${input.dossierDir || `rewind-${input.asOf}`}/${n.ticker}.md`,
    docIds: n.docIds.trim().split(/\\s+/),
    casesPath: n.casesPath || null, rulings: n.rulings || null, overall: n.overall || null,
    edited: n.edited || null,
  }
})

// Training cutoffs, probed by a one-agent call (opus 2026-08-19, the rest
// 2026-09-12). A model whose cutoff falls after the as-of date can recall
// what happened next, so every launch checks the verdict model here.
// Every seat names a VERSIONED id. A bare alias ('sonnet', 'opus', 'fable')
// moves with Anthropic's releases: on 2026-09-28 'sonnet' became Sonnet 5.5
// under a pass rule tuned on Sonnet 5, and nothing failed. So the cutoff table
// holds versioned ids only, and an alias is refused at launch.
const SONNET = 'claude-sonnet-5'
const OPUS = 'claude-opus-4-8'
const VERDICT_MODEL = 'VERDICT_MODEL_VALUE'
const CUTOFF = { 'claude-sonnet-5': '2026-01', 'claude-opus-4-8': '2026-01',
                 'claude-fable-5': '2026-01', 'claude-fable-5-1': '2026-06' }
for (const m of [SONNET, OPUS, VERDICT_MODEL]) {
  if (!/\\d/.test(m)) throw new Error(`${m} is a bare alias; pin a versioned model id`)
  if (!(m in CUTOFF)) throw new Error(`no training cutoff on record for model ${m}; probe it first`)
  if (input.asOf.slice(0, 7) < CUTOFF[m]) {
    throw new Error(`${m} (cutoff ${CUTOFF[m]}) is not blind on ${input.asOf}; a live date only`)
  }
}

// The four tests of a thesis (docs/four-tests.md), one list for every schema.
const TEST_KEYS = TEST_KEYS_JSON
const perTest = (T) => ({
  type: 'object',
  properties: Object.fromEntries(TEST_KEYS.map((k) => [k, T])),
  required: TEST_KEYS,
})

// One argued test: the case, the fact that carries it, the doc ids it rests on.
const CASE_TEST = {
  type: 'object',
  properties: {
    case: { type: 'string', minLength: 200 },
    strongest_fact: { type: 'string', minLength: 20 },
    cites: { type: 'array', minItems: 1, items: { type: 'string' } },
  },
  required: ['case', 'strongest_fact', 'cites'],
}
const CASE_TESTS = perTest(CASE_TEST)
const caseSchema = (ticker, asOf) => ({
  type: 'object',
  properties: {
    ticker: { type: 'string', enum: [ticker] },
    as_of: { type: 'string', enum: [asOf] },
    tests: CASE_TESTS,
  },
  required: ['ticker', 'as_of', 'tests'],
})

// One ruled test, two separate questions: who won, and whether the winning
// side's own evidence is whole. Collapsing those into one word left the
// ruler no way to record a bear who lands a real blow without holing the
// bull's evidence, so it had to rule bull.
const RULING = {
  type: 'object',
  properties: {
    winner: { type: 'string', enum: ['bull', 'bear'] },
    completeness: { type: 'string', enum: ['whole', 'holed'] },
    why: { type: 'string', minLength: 40 },
    cite: { type: 'string' },
  },
  required: ['winner', 'completeness', 'why', 'cite'],
}
const RULINGS = perTest(RULING)
const rulerSchema = (ticker, asOf) => ({
  type: 'object',
  properties: {
    ticker: { type: 'string', enum: [ticker] },
    as_of: { type: 'string', enum: [asOf] },
    tests: RULINGS,
    overall: {
      type: 'object',
      properties: {
        ruling: { type: 'string', enum: ['bull', 'bear'] },
        why: { type: 'string', minLength: 40 },
      },
      required: ['ruling', 'why'],
    },
    struck: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          side: { type: 'string', enum: ['bull', 'bear'] },
          test: { type: 'string', enum: TEST_KEYS },
          claim: { type: 'string' },
          reason: { type: 'string' },
        },
        required: ['side', 'test', 'claim', 'reason'],
      },
    },
  },
  required: ['ticker', 'as_of', 'tests', 'overall', 'struck'],
})

// One edited test: both cases at full strength, and whether the ruling's fact survived.
const EDITED = {
  type: 'object',
  properties: {
    bull: { type: 'string', minLength: 200 },
    bear: { type: 'string', minLength: 200 },
    ruling_stands: { type: 'boolean' },
  },
  required: ['bull', 'bear', 'ruling_stands'],
}
const EDITED_TESTS = perTest(EDITED)
const editorSchema = (ticker, asOf) => ({
  type: 'object',
  properties: {
    ticker: { type: 'string', enum: [ticker] },
    as_of: { type: 'string', enum: [asOf] },
    tests: EDITED_TESTS,
    edit_log: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          side: { type: 'string', enum: ['bull', 'bear'] },
          test: { type: 'string', enum: TEST_KEYS },
          change: { type: 'string', enum: ['strike', 'correct', 'add'] },
          what: { type: 'string' },
          why: { type: 'string' },
          cite: { type: 'string' },
        },
        required: ['side', 'test', 'change', 'what', 'why', 'cite'],
      },
    },
  },
  required: ['ticker', 'as_of', 'tests', 'edit_log'],
})

const verdictSchema = (ticker, asOf) => ({
  type: 'object',
  properties: {
    ticker: { type: 'string', enum: [ticker] },
    as_of: { type: 'string', enum: [asOf] },
    thesis: { type: 'string', minLength: 200 },
    bear_case: {
      type: 'object',
      properties: {
        finding: { type: 'string', minLength: 40 },
        cite: { type: 'string' },
        decisive: { type: 'boolean' },
        ruling: { type: 'string', minLength: 40 },
      },
      required: ['finding', 'cite', 'decisive', 'ruling'],
    },
    rating_basis: { type: 'string', minLength: 60 },
    shortlist: { type: 'boolean' },
    p_outperform: { type: 'number' },
    citations: { type: 'array', items: { type: 'string' } },
  },
  required: ['ticker', 'as_of', 'thesis', 'bear_case', 'rating_basis', 'shortlist', 'p_outperform', 'citations'],
})

const head = (name) =>
  `Candidate ${name.slug}, dossier compiled as of ${name.as_of}.\\n\\n` +
  `===== DOSSIER =====\\nRead this file IN FULL with the Read tool before ` +
  `anything else:\\n${name.dossierPath}\\n===== END DOSSIER =====\\n\\n` +
  `Valid citation doc ids: ${name.docIds.join(', ')}.\\n`
const show = (label, obj) => `===== ${label} =====\\n${JSON.stringify(obj, null, 2)}\\n===== END ${label} =====\\n`

// Stage 3a: the bull and the bear, in parallel, each from the dossier alone.
const casePrompt = (seat, name) =>
  BODY[seat] + '\\n\\n---\\n\\n' + head(name) +
  `Now write the ${seat} case for each of the four tests, via the schema. ` +
  `Use the Read tool for that one file and no other tool.`
const bullCase = (name) => agent(casePrompt('bull', name),
  { model: SONNET, effort: 'high', phase: 'Cases',
    label: `bull:${name.slug}@${name.as_of}`,
    schema: caseSchema(name.slug, name.as_of) })
const bearCase = (name) => agent(casePrompt('bear', name),
  { model: SONNET, effort: 'high', phase: 'Cases',
    label: `bear:${name.slug}@${name.as_of}`,
    schema: caseSchema(name.slug, name.as_of) })
const argueCases = (name) => parallel([() => bullCase(name), () => bearCase(name)])
  .then(([bull, bear]) => (bull && bear) ? { bull, bear } : null)

// Stage 3b: the ruler, dossier first, then both cases inline.
const rule = (name, cases) => agent(
  BODY.ruler + '\\n\\n---\\n\\n' + head(name) + '\\n' +
  show('BULL CASE', cases.bull.tests) + '\\n' + show('BEAR CASE', cases.bear.tests) + '\\n' +
  `Now rule each of the four tests on both questions, the winner and whether ` +
  `that winner's evidence is whole, then rule the whole, and list the claims ` +
  `you gave no weight, all via the schema. Use the Read tool for that one ` +
  `dossier file and no other tool.`,
  { model: SONNET, effort: 'high', phase: 'Ruler',
    label: `ruler:${name.slug}@${name.as_of}`,
    schema: rulerSchema(name.slug, name.as_of) })

// Stage 4: the editor, survivors only. The cases arrive inline from this
// run's ruler, or by path on a stored-cases run (layer verdict).
const casesBlock = (name, cases) => cases
  ? show('BULL CASE', cases.bull.tests) + '\\n' + show('BEAR CASE', cases.bear.tests) + '\\n' + show('RULINGS', cases.ruler.tests)
  : `===== CASES FILE =====\\nAfter the dossier, read this file IN FULL with the Read tool; it ` +
    `holds the bull case, the bear case and the rulings:\\n${name.casesPath}\\n===== END CASES FILE =====\\n`
const edit = (name, cases) => agent(
  BODY.editor + '\\n\\n---\\n\\n' + head(name) + '\\n' + casesBlock(name, cases) + '\\n' +
  `Now check, strike, correct, add and align, both sides, every test, and ` +
  `write the edit log, all via the schema. Use the Read tool for the files ` +
  `named here and no other tool.`,
  { model: OPUS, effort: 'high', phase: 'Editor',
    label: `editor:${name.slug}@${name.as_of}`,
    schema: editorSchema(name.slug, name.as_of) })

// Stage 5: the verdict, survivors only, the one number of record.
// With the rulings withheld, `ruling_stands` goes too: it names a ruling the
// seat cannot see.
const unruled = (tests) => Object.fromEntries(Object.entries(tests).map(
  ([k, v]) => [k, Object.fromEntries(Object.entries(v).filter(([f]) => f !== 'ruling_stands'))]))
const decide = (name, edited, rulings) => agent(
  (WITHHOLD_RULINGS ? BODY.verdict_unruled : BODY.verdict) + '\\n\\n---\\n\\n' + head(name) + '\\n' +
  (WITHHOLD_RULINGS
    ? show('THE TWO CASES, EDITED', unruled(edited.tests)) + '\\n'
    : show('THE TWO CASES, EDITED', edited.tests) + '\\n' + show('RULINGS', rulings) + '\\n') +
  `Now write the thesis with its driver first, build the whole-company bear ` +
  `case and rule on it, set shortlist, then name the class you are rating ` +
  `against in rating_basis and place this name inside it before you set ` +
  `p_outperform, all via the schema. Use the Read tool for that one dossier ` +
  `file and no other tool.`,
  { model: VERDICT_MODEL, effort: 'high', phase: 'Verdict',
    label: `verdict:${name.slug}@${name.as_of}`,
    schema: verdictSchema(name.slug, name.as_of) })

// Downstream seats and the scorer read one word per test. A bear winner is
// `bear`; a bull winner is `bull` when its evidence is whole and `gap` when
// holed, which is exactly the old vocabulary, so nothing downstream changes.
const rulingWords = (ruler) => Object.fromEntries(
  Object.entries(ruler.tests).map(([k, v]) =>
    [k, v.winner === 'bear' ? 'bear' : (v.completeness === 'holed' ? 'gap' : 'bull')]))

log(`funnel (${LAYER}, rule ${PASS_RULE}): ${names.length} names for ${input.asOf}`)

const records = await pipeline(
  names,
  // The middle layer: cases, then the ruler, then the pass rule in code.
  async (name) => {
    if (LAYER === 'verdict' || LAYER === 'editor' || LAYER === 'decide') return { name, cases: null, rulings: name.rulings, overall: name.overall, pass: true }
    const cases = await argueCases(name)
    if (!cases) return null
    const ruler = await rule(name, cases)
    if (!ruler) return null
    const rulings = rulingWords(ruler)
    return { name, cases: { ...cases, ruler }, rulings, overall: ruler.overall.ruling, pass: passes(rulings, ruler.overall.ruling) }
  },
  // The final layer, survivors only: editor, then the verdict.
  async (mid) => {
    if (!mid) return null
    const { name, cases, rulings, overall, pass } = mid
    const base = { slug: name.slug, as_of: name.as_of, ruler_pass: pass, overall, rulings,
                   ...(cases ? { cases } : { casesPath: name.casesPath }) }
    if (LAYER === 'middle' || !pass) return { ...base, shortlist: false, p_judge: null, thesis: null }
    const edited = LAYER === 'decide' ? { tests: name.edited, edit_log: [] } : await edit(name, cases)
    if (!edited) return null
    // Editor only: recover the checked cases for names whose verdict is already on
    // record, without re-running the verdict.
    if (LAYER === 'editor') return { ...base, edited_cases: edited.tests, edit_log: edited.edit_log }
    const v = await decide(name, edited, rulings)
    if (!v) return null
    return { ...base, edited_cases: edited.tests, edit_log: edited.edit_log, shortlist: v.shortlist, p_judge: v.p_outperform,
             thesis: v.thesis, bear_case: v.bear_case, rating_basis: v.rating_basis, citations: v.citations }
  },
)

const done = records.filter(Boolean)
const dropped = names
  .map((n) => `${n.slug}@${n.as_of}`)
  .filter((k) => !done.some((r) => `${r.slug}@${r.as_of}` === k))
if (dropped.length > 0) log(`WARNING: dropped by agent errors — rerun, never silently skip: ${dropped.join(' ')}`)
const passed = done.filter((r) => r.ruler_pass).length
const listed = done.filter((r) => r.shortlist).length
log(`funnel complete: ${done.length} of ${names.length}; ruler passed ${passed}; shortlisted ${listed}`)
return { summary: done, dropped, layer: LAYER, passRule: PASS_RULE }
"""


# Unit 11j: the two sentences that tell the verdict the rulings arrive. With
# the rulings withheld they would describe input the seat never gets.
_UNRULED = (
    ("then the two\ncases and the four rulings, which arrive inline.", "then the two\ncases, which arrive inline."),
    ("1. Read the full dossier, then the two cases and the rulings.", "1. Read the full dossier, then the two cases."),
)


def unruled_body() -> str:
    text = body("verdict")
    for old, new in _UNRULED:
        if text.count(old) != 1:
            raise ValueError(f"verdict body anchor moved: {old!r}")
        text = text.replace(old, new)
    return text


def generate(pass_rule: str = "overall", verdict_model: str = OPUS,
             withhold_rulings: bool = False) -> str:
    if pass_rule not in PASS_RULES:
        raise ValueError(f"pass rule must be one of {PASS_RULES}, got {pass_rule}")
    script = _TEMPLATE.replace("TEST_KEYS_JSON", json.dumps(list(four_tests.KEYS)))
    script = script.replace("PASS_RULE_VALUE", pass_rule)
    script = script.replace("VERDICT_MODEL_VALUE", verdict_model)
    script = script.replace("WITHHOLD_RULINGS_VALUE", "true" if withhold_rulings else "false")
    # embedded only on a withheld run, so the funnel of record carries one verdict body
    script = script.replace("BODY_VERDICT_UNRULED_JSON",
                            json.dumps(unruled_body()) if withhold_rulings else "null")
    for seat in SEATS:
        marker = f"BODY_{seat.upper()}_JSON"
        if marker not in script:
            raise ValueError(f"anchor {marker} missing")
        script = script.replace(marker, json.dumps(body(seat)))
    return script


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--pass-rule", choices=PASS_RULES, default="overall")
    ap.add_argument("--verdict-model", default=VERDICT,
                    help="a model is refused at launch on any date before its cutoff")
    ap.add_argument("--withhold-rulings", action="store_true",
                    help="unit 11j: the verdict reads the edited cases without the ruler's words")
    args = ap.parse_args(argv)
    script = generate(args.pass_rule, args.verdict_model, args.withhold_rulings)
    args.out.write_text(script)
    print(f"wrote {args.out} ({len(script)} bytes, rule {args.pass_rule}, verdict {args.verdict_model})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
